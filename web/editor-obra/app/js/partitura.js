/* Soul Charger editor · PARTITURA: links the score to DA_Partitura_Obra (the director's timing knobs in Unreal).
   Pure (no DOM): runs in the browser and in Node (tools/editor/partitura_drift.mjs).
   def     = obra/unreal/partitura_def.json (knob names/types/initial values, synced from tools/unreal/partitura_def.py)
   live    = obra/unreal/partitura.json (live values exported from the DA by the director) — optional
   binding = obra/unreal/partitura_binding.json (which score elements each knob governs, and how to measure it; `ids`: the
             elements frozen by id, so a rename never loses them — tools/score/bind_ids.mjs) */
(function (root) {
  'use strict';
  const NSTAGES = 5;
  const pick = (v, K) => (v && typeof v === 'object' && !Array.isArray(v)) ? (K != null && v[K] !== undefined ? v[K] : v['*']) : v;
  const fill = (s, K, binding) => typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (_, n) => (binding.stageBeats[n] || [])[K]) : s;

  function index(score) {
    const beatByKey = {}, inBeat = {};
    for (const id in score.beats) beatByKey[score.beats[id].key] = id;
    for (const id in score.elements) { const e = score.elements[id]; (inBeat[e.beat] = inBeat[e.beat] || []).push(id); }
    return { beatByKey, inBeat };
  }
  // element id (or beat id for '@beat') of `el` inside moment `beatKey`
  function find(score, sched, ix, beatKey, el) {
    const b = ix.beatByKey[beatKey]; if (!b) return null;
    if (el === '@beat') return b;
    const ids = (ix.inBeat[b] || []).slice().sort((x, y) => sched.t[x][0] - sched.t[y][0]);
    if (el === '@firstVO' || el === '@lastVO') { const v = ids.filter(id => score.elements[id].type === 'vo' && !score.elements[id].help); return v.length ? (el === '@firstVO' ? v[0] : v[v.length - 1]) : null; }
    return ids.find(id => score.elements[id].key === el) || null;
  }
  const edgeT = (sched, id, edge) => sched.t[id] ? sched.t[id][edge === 'end' ? 1 : 0] : null;
  /* the element a bind (or an origin) names, lote 5 design A §7.2: its frozen id (`ids`, generated by tools/score/bind_ids.mjs)
     while that element is still in the expected moment and, for '@firstVO'/'@lastVO', still the first/last voice there; a
     rename never loses it. Otherwise the lookup by key, and why in `stale` (C3.BINDING.STALE). Without ids: by key, as before */
  function locate(score, sched, ix, beat, el, frozen, stale) {
    if (frozen == null || el === '@beat') return find(score, sched, ix, beat, el);
    const e = score.elements[frozen], b = e && score.beats[e.beat], order = el === '@firstVO' || el === '@lastVO';
    if (b && b.key === beat && (!order || find(score, sched, ix, beat, el) === frozen)) return frozen;
    const now = find(score, sched, ix, beat, el);
    stale.push({ id: frozen, key: e ? e.key : null, el, beat, why: !e ? 'gone' : b && b.key === beat ? 'order' : 'moved', now, nowKey: now && score.elements[now] ? score.elements[now].key : null });
    return now;
  }
  // the frozen id of stage K ('*' when the bind is one value for all), the i-th one of a gap
  const frozenOf = (x, K, i) => { const v = x.ids && x.ids[K == null ? '*' : K]; return Array.isArray(v) ? v[i] : i ? undefined : v; };

  /* value of one knob (one stage) measured on the score, plus the element ids it governs (and the origin it is measured from).
     `stale`: the frozen ids that no longer hold (the measure then used the key lookup) */
  function measure(score, sched, binding, bind, K, ix) {
    ix = ix || index(score);
    const m = bind.m, beat = fill(pick(m.beat, K), K, binding);
    if (!beat) return null;
    const out = { value: null, els: [] }, stale = [];
    const failed = () => stale.length ? { value: null, els: [], stale } : null;
    if (m.kind === 'dur' || m.kind === 'fw' || m.kind === 'start' || m.kind === 'end') {
      const id = locate(score, sched, ix, beat, pick(m.el, K), frozenOf(bind, K, 0), stale); if (!id) return failed();
      out.els.push(id);
      if (m.kind === 'dur') out.value = sched.t[id][1] - sched.t[id][0];
      else if (m.kind === 'fw') { const g = score.elements[id].gate; if (!g) return failed(); out.value = g.fw; }
      else {
        const o = binding.origins[m.from], ob = fill(pick(o.beat, K), K, binding), oid = locate(score, sched, ix, ob, pick(o.el, K), frozenOf(o, K, 0), stale);
        if (!oid) return failed();
        out.origin = oid; out.value = edgeT(sched, id, m.kind) - edgeT(sched, oid, o.edge);
      }
    } else if (m.kind === 'gap') {
      const a = locate(score, sched, ix, beat, m.a[0], frozenOf(bind, K, 0), stale), b = locate(score, sched, ix, beat, m.b[0], frozenOf(bind, K, 1), stale);
      if (!a || !b) return failed();
      out.els.push(a, b); out.value = edgeT(sched, b, m.b[1]) - edgeT(sched, a, m.a[1]);
    }
    if (out.value != null) out.value = Math.round(out.value * 1000) / 1000;
    if (stale.length) out.stale = stale;
    return out;
  }

  // the director's export: {exportado, hash, asset, valores}
  const liveValues = live => live ? (live.valores || live.values || null) : null;

  /* bring ONE knob (one stage, or all) to `value` in the score: inverse of measure(). Mutates `score`.
     Returns {changed:[ids], skipped:[{stage, why}]}. Re-resolves between stages so chained elements stay coherent. */
  function apply(score, Engine, binding, bind, value, stage) {
    const out = { changed: [], skipped: [] }, ix = index(score);
    const stages = bind.perStage ? (stage == null ? [...Array(NSTAGES).keys()] : [stage]) : [null];
    for (const s of stages) {
      const want = Array.isArray(value) ? value[s == null ? 0 : s] : value;
      const sched = Engine.resolve(score, { persona: 'typical' });
      const r = measure(score, sched, binding, bind, s, ix);
      if (!r || r.value == null) { out.skipped.push({ stage: s, why: 'no counterpart in the score' }); continue; }
      const delta = Math.round((want - r.value) * 10000) / 10000; if (Math.abs(delta) < 1e-4) continue;
      const m = bind.m, last = r.els[r.els.length - 1], e = score.elements[last];
      if (m.kind === 'fw') { e.gate.fw = want; out.changed.push(last); continue; }
      if (m.kind === 'start' || m.kind === 'gap') {
        // move the element (its anchored family follows); a fixed-length element keeps its length
        if (!e.at) { out.skipped.push({ stage: s, why: e.key + ' has no anchor' }); continue; }
        e.at.off = Math.round((e.at.off + delta) * 10000) / 10000; out.changed.push(last); continue;
      }
      // dur / end: change the length (only fixed lengths can change; voice = its audio, 'until' = its anchor)
      if (e.gate) { out.skipped.push({ stage: s, why: e.key + ' is a wait: its length is the user' }); continue; }
      if (!e.dur || !(e.dur.mode === 'fixed' || e.dur.mode === 'instant')) { out.skipped.push({ stage: s, why: e.key + ' lasts ' + (e.dur ? e.dur.mode : '?') + ': its length cannot be set' }); continue; }
      const cur = sched.t[last][1] - sched.t[last][0];
      e.dur = { mode: 'fixed', value: Math.max(0, Math.round((cur + delta) * 10000) / 10000) }; out.changed.push(last);
    }
    return out;
  }

  /* every bound knob: the DA value vs what the score does today */
  function drift(score, sched, def, live, binding) {
    const ix = index(score), K = {}, rows = [];
    for (const k of def.knobs) K[k.name] = k;
    const LV = liveValues(live);
    const valOf = name => (LV && name in LV) ? LV[name] : (K[name] ? K[name].initial : null);
    for (const bind of binding.binds) {
      const kd = K[bind.knob]; if (!kd) { rows.push({ knob: bind.knob, missing: true }); continue; }
      const da = valOf(bind.knob);
      const stages = bind.perStage ? [...Array(NSTAGES).keys()] : [null];
      for (const s of stages) {
        const r = measure(score, sched, binding, bind, s, ix);
        const want = Array.isArray(da) ? da[s == null ? 0 : s] : da;
        rows.push(Object.assign({ knob: bind.knob, stage: s, da: want, score: r ? r.value : null, els: r ? r.els : [], approx: bind.approx || null,
          diff: r && r.value != null && want != null ? Math.round((r.value - want) * 1000) / 1000 : null }, r && r.stale ? { stale: r.stale } : {}));
      }
    }
    return { source: live ? 'live' : 'initial', rows };
  }
  /* C3.BINDING.STALE (info), one per frozen element and stage: a bind whose element no longer holds (deleted, moved to another
     moment, no longer the first/last voice); meanwhile the score is measured by key. The binding file is regenerated by
     tools/score/bind_ids.mjs, never by the app. names = the stage names (partitura_def.json `stages`) */
  function staleProblems(dr, names) {
    const by = new Map();
    for (const r of (dr && dr.rows) || []) for (const x of r.stale || []) {
      const k = x.id + '|' + (r.stage == null ? '' : r.stage);
      if (!by.has(k)) by.set(k, { x, stage: r.stage, knobs: [] });
      const g = by.get(k); if (!g.knobs.includes(r.knob)) g.knobs.push(r.knob);
    }
    return [...by.entries()].map(([k, { x, stage, knobs }]) => {
      const where = stage == null ? '' : ` (${(names && names[stage]) || 'stage ' + (stage + 1)})`, name = x.key || (x.el && x.el[0] !== '@' ? x.el : x.el === '@firstVO' || x.el === '@lastVO' ? `the ${x.el === '@firstVO' ? 'first' : 'last'} voice of moment ${x.beat}` : 'the element it was bound to');
      const why = x.why === 'gone' ? `${name} is no longer in the score` : x.why === 'order' ? `${name} is no longer the ${x.el === '@firstVO' ? 'first' : 'last'} voice of moment ${x.beat}` : `${name} is no longer in moment ${x.beat}`;
      return { fp: 'C3.BINDING.STALE|' + k, sv: 'info', ly: 'C3', rule: 'C3.BINDING.STALE', knob: knobs[0], el: x.why === 'gone' ? x.now || null : x.id, own: 'partitura_binding.json › ' + knobs.join(', '), st: 'open',
        msg: `${knobs.join(', ')}${where}: ${why}; ${knobs.length > 1 ? 'they are' : 'it is'} measured on ${x.nowKey || 'nothing'} by name until the binding is regenerated (tools/score/bind_ids.mjs).` };
    });
  }
  /* element id → [{knob, stage}] it is governed by (for the inspector) */
  function governedBy(score, sched, binding) {
    const ix = index(score), map = {};
    for (const bind of binding.binds) for (const s of (bind.perStage ? [...Array(NSTAGES).keys()] : [null])) {
      const r = measure(score, sched, binding, bind, s, ix); if (!r) continue;
      for (const id of r.els) if (score.elements[id]) (map[id] = map[id] || []).push({ knob: bind.knob, stage: s });
    }
    return map;
  }
  /* what a set of knob values would break in Unreal, BEFORE sending it: order of the reveals, minimums, big jumps.
     vals = the full set as it would end up in the DA (live values + the proposed ones); before = live values.
     Returns [{sv:'block'|'warn', knob, msg}]: a 'block' cannot be sent. */
  const ORDER = [
    ['Titulo_RevelaIni', 'Titulo_RevelaFin', 'the Hall title must finish revealing after it starts'],
    ['Bajada_RevelaIni', 'Bajada_RevelaFin', 'the subtitle must finish revealing after it starts'],
    ['Logos_RevelaIni', 'Logos_RevelaFin', 'the logos must finish revealing after they start'],
    ['Titulo_RevelaFin', 'Titulo_SaleIni', 'the Hall title must be fully revealed before it starts to leave'],
    ['Titulo_SaleIni', 'Titulo_SaleFin', 'the Hall title must finish leaving after it starts'],
    ['Titulo_SaleFin', 'Titulo_Fin', 'the title actor is hidden only after it has left'],
    ['Hall_VeloAbreIni', 'Hall_VeloAbreFin', 'the Hall veil must finish opening after it starts'],
    ['Etapa_VeloAbreIni', 'Etapa_VeloAbreFin', 'the stage veil must finish opening after it starts'],
    ['Etapa_TituloRevelaIni', 'Etapa_TituloRevelaFin', 'the stage title must finish revealing after it starts'],
    ['Etapa_TituloRevelaFin', 'Etapa_TituloSaleIni', 'the stage title must be fully revealed before it starts to leave'],
    ['Etapa_TituloSaleIni', 'Etapa_TituloSaleFin', 'the stage title must finish leaving after it starts'],
    ['Etapa_TituloSaleFin', 'Etapa_TituloOculto', 'the stage title is hidden only after it has left'],
    ['Regreso_VeloIni', 'Regreso_VeloFin', 'the return veil must finish opening after it starts'],
    ['Res_PezMin', 'Res_PezMax', 'the soul settles between a minimum and a maximum'],
  ];
  function checks(vals, before, def) {
    const out = [], v = n => vals[n], num = x => typeof x === 'number' && isFinite(x);
    for (const [a, b, why] of ORDER) if (num(v(a)) && num(v(b)) && !(v(a) < v(b) || (b === 'Titulo_Fin' || b === 'Etapa_TituloOculto') && v(a) <= v(b)))
      out.push({ sv: 'block', knob: vals.__changed && vals.__changed.has(a) ? a : b, msg: `${a} ${v(a)} s → ${b} ${v(b)} s: ${why}.` });
    const cd = v('Carga_Dur');
    if (Array.isArray(cd) && num(v('Carga_Minima')) && Math.min(...cd) < v('Carga_Minima')) out.push({ sv: 'block', knob: 'Carga_Dur', msg: `A charge shorter than Carga_Minima (${v('Carga_Minima')} s) can never close.` });
    if (num(v('Res_Tope')) && num(v('Res_Explorar')) && v('Res_Tope') < v('Res_Explorar') + 30) out.push({ sv: 'warn', knob: 'Res_Tope', msg: `Res_Tope ${v('Res_Tope')} s leaves less than 30 s beyond the exploration (${v('Res_Explorar')} s): the results could be cut by the firewall.` });
    for (const k of (def ? def.knobs : [])) {
      const n = k.name; if (!vals.__changed || !vals.__changed.has(n)) continue;
      const a = [].concat(before[n]), b = [].concat(vals[n]);
      b.forEach((x, i) => {
        if (!num(x) || x < 0) out.push({ sv: 'block', knob: n, msg: `${n}: ${x} is not a valid time.` });
        else if (num(a[i]) && Math.abs(x - a[i]) > Math.max(5, a[i] * .5)) out.push({ sv: 'warn', knob: n, msg: `${n}${b.length > 1 ? ' [' + i + ']' : ''}: big jump, ${a[i]} → ${x} s.` });
        if (n === 'Etapa_Tope' && num(x) && x < 30) out.push({ sv: 'warn', knob: n, msg: `Etapa_Tope [${i}] = ${x} s: the mechanic would be asked to close almost at once.` });
      });
      if (n === 'Carga_Dur' && num(b[4]) && num(a[4]) && b[4] !== a[4]) out.push({ sv: 'warn', knob: n, msg: 'Carga_Dur[4] is the final charge: ReadCharge and FlowVeil move with it in Unreal (that is expected).' });
    }
    return out;
  }
  const api = { measure, drift, governedBy, apply, liveValues, checks, staleProblems };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.Partitura = api;
})(typeof window !== 'undefined' ? window : globalThis);
