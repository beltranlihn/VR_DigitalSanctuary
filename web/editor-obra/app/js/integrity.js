        const title = { literal: 'Hardwired in Unreal', wired: 'Called by Unreal', knob: 'Knob in Unreal', partitura: 'Unreal timing knob', 'not-blocking': 'Different in Unreal', 'not-in-unreal': 'Not in Unreal' }[c.kind] || 'Unreal';
        const apk = apkOf(id, verb), bef = sv !== 'info' ? beforeOf(accepted, base, rule) : null;
